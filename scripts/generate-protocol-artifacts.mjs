#!/usr/bin/env node

/**
 * Synchronise generated protocol metadata after an Anchor change or a Devnet
 * deployment. The Anchor program remains the source of truth; this script
 * only materialises values consumed by TypeScript and the Rust prover crate.
 */
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));

function option(name, fallback = undefined) {
  const index = process.argv.indexOf(name);
  return index === -1 ? fallback : process.argv[index + 1];
}

function requiredOption(name) {
  const value = option(name);
  if (!value) throw new Error(`${name} requires a value`);
  return value;
}

async function text(path) {
  return readFile(resolve(root, path), "utf8");
}

function rustConst(source, name) {
  const match = source.match(
    new RegExp(`pub const ${name}\\s*:\\s*[^=;]+\\s*=\\s*([^;]+);`),
  );
  if (!match) throw new Error(`could not find Rust constant ${name}`);
  return match[1].trim();
}

function numeric(value, label) {
  const match = value.match(/^([0-9_]+)(?:u(?:8|16|32|64|128))?$/);
  if (!match) throw new Error(`${label} is not a numeric Rust constant: ${value}`);
  return Number(match[1].replaceAll("_", ""));
}

function anchorProgramId(anchorToml, cluster) {
  const section = new RegExp(
    `\\[programs\\.${cluster}\\]([\\s\\S]*?)(?:\\n\\[|$)`,
  ).exec(anchorToml)?.[1];
  const id = section?.match(/^beatex\s*=\s*"([1-9A-HJ-NP-Za-km-z]+)"/m)?.[1];
  if (!id) throw new Error(`could not find beatex program ID for ${cluster}`);
  return id;
}

async function parseTsv(path) {
  try {
    const lines = (await readFile(path, "utf8")).trim().split(/\r?\n/);
    const values = new Map();
    for (const line of lines.slice(1)) {
      const [name, value] = line.split("\t");
      if (name && value) values.set(name, value);
    }
    return values;
  } catch (error) {
    if (error.code === "ENOENT") return new Map();
    throw error;
  }
}

const cluster = option("--cluster", "devnet");
const stateDirArg = option("--state-dir");
const stateDir = stateDirArg
  ? resolve(root, stateDirArg)
  : resolve(root, `.devnet/${cluster}`);
const anchorToml = await text("Anchor.toml");
const state = await text("programs/beatex/src/state.rs");
const queue = await text("programs/beatex/src/queue.rs");
const programId = option("--program-id", anchorProgramId(anchorToml, cluster));

const protocol = {
  protocolVersion: numeric(rustConst(state, "PROTOCOL_VERSION"), "PROTOCOL_VERSION"),
  gridRadius: numeric(rustConst(state, "MAX_GRID_RADIUS"), "MAX_GRID_RADIUS"),
  gridStepBps: numeric(rustConst(state, "DEFAULT_GRID_STEP_BPS"), "DEFAULT_GRID_STEP_BPS"),
  baseUnitSize: numeric(rustConst(state, "BASE_UNIT_SIZE"), "BASE_UNIT_SIZE"),
  quoteUnitSize: numeric(rustConst(state, "QUOTE_UNIT_SIZE"), "QUOTE_UNIT_SIZE"),
  quantityBits: numeric(
    rustConst(queue, "PRIVATE_ORDER_QUANTITY_BITS"),
    "PRIVATE_ORDER_QUANTITY_BITS",
  ),
  circuitVersions: Object.fromEntries(
    [
      "ORDER_SUBMISSION",
      "BALANCE_DEPOSIT",
      "AGGREGATE_FOLD",
      "AGGREGATE_PUBLICATION",
      "ORDER_MODIFICATION",
      "ROLLOVER_SETTLEMENT",
      "PRIVATE_CLAIM",
      "CANCELLATION_REFUND",
    ].map((name) => [
      name,
      numeric(rustConst(queue, `${name}_CIRCUIT_VERSION`), `${name}_CIRCUIT_VERSION`),
    ]),
  ),
};

const market = await parseTsv(resolve(stateDir, "market.tsv"));
const marketAddresses = await parseTsv(resolve(stateDir, "market-addresses.tsv"));
const tokenAddresses = await parseTsv(resolve(stateDir, "addresses.tsv"));
const deployment = {
  schemaVersion: 1,
  cluster,
  programId,
  market: market.get("market") ?? null,
  vaultAuthority: market.get("vault-authority") ?? marketAddresses.get("vault-authority") ?? null,
  keyEpoch: market.get("key-epoch") ?? marketAddresses.get("key-epoch") ?? null,
  baseMint: tokenAddresses.get("tBTC") ?? null,
  quoteMint: tokenAddresses.get("tUSD") ?? null,
  baseVault: market.get("base-vault") ?? null,
  quoteVault: market.get("quote-vault") ?? null,
  verificationKeys: Object.fromEntries(
    [...market.entries()]
      .filter(([name]) => name.startsWith("vk-"))
      .map(([name, value]) => [name, value]),
  ),
  protocol,
};

const idlPath = option("--idl");
if (idlPath) {
  deployment.idlSha256 = createHash("sha256")
    .update(await readFile(resolve(root, idlPath)))
    .digest("hex");
}
const generatedDeployment = JSON.stringify(deployment, null, 2);
const sdkGenerated = `/**\n * Generated by scripts/generate-protocol-artifacts.mjs.\n * Do not edit manually; rerun the build or Devnet setup pipeline.\n */\nexport const GENERATED_CLUSTER = ${JSON.stringify(cluster)};\nexport const GENERATED_PROGRAM_ID = ${JSON.stringify(programId)};\nexport const GENERATED_MARKET_ID: string | null = ${JSON.stringify(deployment.market)};\nexport const GENERATED_DEPLOYMENT = ${generatedDeployment} as const;\n`;
const rustGenerated = `// Generated by scripts/generate-protocol-artifacts.mjs.\n// Do not edit manually; rerun the build pipeline after changing the Anchor program.\npub const PROTOCOL_VERSION: u8 = ${protocol.protocolVersion};\npub const LEVELS: usize = ${protocol.gridRadius * 2 + 1};\npub const GRID_RADIUS: usize = ${protocol.gridRadius};\npub const BPS_DENOMINATOR: u64 = 10_000;\npub const DEFAULT_GRID_STEP_BPS: u16 = ${protocol.gridStepBps};\npub const BASE_UNIT_SIZE: u64 = ${protocol.baseUnitSize};\npub const QUOTE_UNIT_SIZE: u64 = ${protocol.quoteUnitSize};\npub const QUANTITY_BITS: usize = ${protocol.quantityBits};\npub const MAX_ORDER_QUANTITY: u64 = (1_u64 << QUANTITY_BITS) - 1;\n${Object.entries(protocol.circuitVersions)
  .map(([name, value]) => `pub const ${name}_CIRCUIT_VERSION: u16 = ${value};`)
  .join("\n")}\n`;

await mkdir(resolve(root, "packages/sdk/src/protocol"), { recursive: true });
await mkdir(resolve(root, "crates/babyjubjub-groth16-spike/src"), { recursive: true });
await writeFile(resolve(root, "packages/sdk/src/protocol/generated.ts"), sdkGenerated);
await writeFile(
  resolve(root, "crates/babyjubjub-groth16-spike/src/generated_protocol.rs"),
  rustGenerated,
);
await mkdir(stateDir, { recursive: true });
await writeFile(
  resolve(stateDir, "deployment.json"),
  `${JSON.stringify({ ...deployment, generatedAt: new Date().toISOString() }, null, 2)}\n`,
);

console.log(`Generated SDK/Rust protocol artifacts for ${cluster}.`);
console.log(`Deployment manifest: ${resolve(stateDir, "deployment.json")}`);
